/**
 * Generates seed/chrono.sql from chronological-order.csv.
 *
 *   node scripts/generate-chrono-seed.mjs
 *
 * Unlike items.sql this is UPDATEs, not inserts: chrono_order and
 * chrono_setting are matched onto existing items.items by title, since the
 * two CSVs don't share an id space (the chrono file has its own "#", with a
 * gap where a row was inserted after numbering was fixed).
 *
 * Matching is by id, not by "WHERE title = ...": seed-data.csv has duplicate
 * titles (six "Untitled Marvel Film" rows), and a title-keyed UPDATE would
 * silently apply one chrono row's placement to every item sharing that title.
 * A title that maps to more than one item id is treated as ambiguous and
 * skipped with a warning rather than guessed at.
 *
 * chrono_order is the row's position in the file (1..112) including the
 * separator row and the one row with a blank "#" — it is a stable position,
 * not the CSV's own numbering, precisely because that numbering has a gap.
 *
 * Items with no title match get chrono_order = NULL implicitly (the column
 * default), which chronological.js renders as a trailing "not yet placed"
 * section rather than dropping them from the page.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "chronological-order.csv");
const OUT = join(ROOT, "seed", "chrono.sql");
const ITEMS_SRC = join(ROOT, "seed-data.csv");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
      continue;
    }
    if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\r") {
      // ignore
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  const s = String(value).trim();
  if (s === "") return "NULL";
  return `'${s.replace(/'/g, "''")}'`;
}

function readRows(path) {
  const raw = readFileSync(path, "utf8").replace(/^﻿/, "");
  const rows = parseCsv(raw).filter((r) => r.some((c) => c.trim() !== ""));
  const header = rows.shift().map((h) => h.trim());
  const col = (name) => {
    const i = header.indexOf(name);
    if (i === -1) throw new Error(`${path}: missing expected column ${name}`);
    return i;
  };
  return { header, col, rows };
}

const chrono = readRows(SRC);
const C = {
  title: chrono.col("Title"),
  setting: chrono.col("Chrono Setting"),
};

const items = readRows(ITEMS_SRC);
const IC = { num: items.col("#"), title: items.col("Title") };

// title -> [ids]; duplicate titles collapse into a multi-entry list so
// ambiguity can be detected instead of silently resolved.
const idsByTitle = new Map();
for (const r of items.rows) {
  const t = r[IC.title].trim();
  const id = Number(r[IC.num]);
  if (!idsByTitle.has(t)) idsByTitle.set(t, []);
  idsByTitle.get(t).push(id);
}
const totalItems = items.rows.length;

const statements = [];
const placedIds = new Set();
const report = { placed: 0, skippedSeparator: 0, unmatchedTitle: [], ambiguousTitle: [] };

chrono.rows.forEach((r, i) => {
  const title = (r[C.title] ?? "").trim();
  const setting = (r[C.setting] ?? "").trim();
  const order = i + 1; // stable file position, not the CSV's own "#"

  if (title.startsWith("---")) {
    // The "OUTSIDE THE SACRED TIMELINE" separator is a section marker in the
    // source spreadsheet, not a title — it has no items.id to attach to.
    report.skippedSeparator++;
    return;
  }

  const ids = idsByTitle.get(title);
  if (!ids) {
    report.unmatchedTitle.push(title);
    return;
  }
  if (ids.length > 1) {
    report.ambiguousTitle.push({ title, ids });
    return;
  }

  const id = ids[0];
  statements.push(
    `UPDATE items SET chrono_order = ${order}, chrono_setting = ${sql(setting)} WHERE id = ${id};`
  );
  placedIds.add(id);
  report.placed++;
});

const unplacedCount = totalItems - placedIds.size;

const out = `-- Generated by scripts/generate-chrono-seed.mjs from chronological-order.csv.
-- Do not edit by hand.
-- Placed: ${report.placed} | separator row skipped: ${report.skippedSeparator}
-- Unmatched titles: ${report.unmatchedTitle.length} | ambiguous titles: ${report.ambiguousTitle.length}
-- Items left with chrono_order = NULL (no chronological placement yet): ${unplacedCount}

${statements.join("\n")}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);

console.log(`wrote ${OUT}`);
console.log(`  placed:              ${report.placed} (by item id)`);
console.log(`  separator skipped:   ${report.skippedSeparator}`);
console.log(`  unmatched titles:    ${report.unmatchedTitle.length}`);
for (const t of report.unmatchedTitle) console.log(`    - ${t}`);
console.log(`  ambiguous titles:    ${report.ambiguousTitle.length}`);
for (const a of report.ambiguousTitle) console.log(`    - "${a.title}" -> ids ${a.ids.join(", ")}`);
console.log(`  items left unplaced (chrono_order NULL): ${unplacedCount} / ${totalItems}`);
