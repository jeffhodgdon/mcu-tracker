/**
 * Generates seed/other-universes.sql from every-universe.csv.
 *
 *   node scripts/generate-other-universes-seed.mjs
 *
 * The CSV encodes its section headers as rows with a filled "Universe /
 * Studio" cell and every other cell blank — that value applies to all
 * following title rows until the next section header, spreadsheet-style, and
 * is carried onto each row explicitly here since the flat other_universes
 * table has no header rows of its own.
 *
 * The CSV has no "#" column, so rows have no stable id of their own to
 * upsert on. The seed must never clear and reinsert the table: that hands
 * every row a new id, and watch_status and watchlist (source = 'other') both
 * point at other_universes.id, so users would silently lose their marks.
 * Instead each row is inserted only if no row with the same (universe,
 * title) exists yet. Existing rows are never updated, so admin edits —
 * chrono_order and is_estimate above all, which the CSV doesn't even carry —
 * survive a re-run. Corrections to an existing row go through the Admin page.
 *
 * Rows titled "-> ..." are skipped. They point at an MCU title that crosses
 * over into this universe, and those now live on items.crossover_universe
 * (/api/other-universes merges them in). Seeding them here would add a
 * second, untracked copy of the same title.
 *
 * A few Release Date values are year-only ("1994") rather than full ISO
 * dates. Those are kept as-is in release_date for display; nothing sorts or
 * does date arithmetic on this table, so a non-ISO value is not a correctness
 * problem the way it would be for items.release_date.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "every-universe.csv");
const OUT = join(ROOT, "seed", "other-universes.sql");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
      continue;
    }
    if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\r") {
      // ignore
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  const s = String(value).trim();
  if (s === "") return "NULL";
  return `'${s.replace(/'/g, "''")}'`;
}

function num(value) {
  const s = String(value ?? "").trim();
  if (!/^\d+$/.test(s)) return null; // covers blank, "-", "TBD"
  return Number(s);
}

const raw = readFileSync(SRC, "utf8").replace(/^﻿/, "");
const rows = parseCsv(raw).filter((r) => r.some((c) => c.trim() !== ""));
const header = rows.shift().map((h) => h.trim());
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`missing expected column: ${name}`);
  return i;
};

const C = {
  universe: col("Universe / Studio"),
  title: col("Title"),
  setting: col("In-Universe Setting"),
  release: col("Release Date"),
  runtime: col("Runtime (min)"),
  notes: col("Notes"),
};

let currentUniverse = null;
const values = [];
let sectionCount = 0;
let titleCount = 0;
let crossoverCount = 0;

for (const r of rows) {
  const universeCell = (r[C.universe] ?? "").trim();
  const title = (r[C.title] ?? "").trim();

  if (universeCell && !title) {
    currentUniverse = universeCell;
    sectionCount++;
    continue;
  }
  if (!title) continue; // stray blank row, if any
  if (title.startsWith("->")) {
    crossoverCount++;
    continue;
  }

  values.push(
    `  (${sql(currentUniverse)}, ${sql(title)}, ${sql(r[C.setting])}, ` +
      `${sql(r[C.release])}, ${num(r[C.runtime]) ?? "NULL"}, ${sql(r[C.notes])})`
  );
  titleCount++;
}

const out = `-- Generated by scripts/generate-other-universes-seed.mjs from every-universe.csv.
-- Do not edit by hand.
-- Universes: ${sectionCount} | title rows: ${titleCount} | crossover rows skipped: ${crossoverCount}
--
-- Safe to re-run. Inserts only rows whose (universe, title) is not already
-- present and never updates or deletes, so existing ids — which watch_status
-- and watchlist point at — and admin edits (chrono_order, is_estimate, ...)
-- are left alone. Rows deleted on purpose come back if re-run, except the
-- "-> ..." crossover rows, which this generator skips (see its header).

INSERT INTO other_universes (universe, title, setting, release_date, runtime_min, notes)
SELECT * FROM (VALUES
${values.join(",\n")}
) AS v
WHERE NOT EXISTS (
  SELECT 1 FROM other_universes o WHERE o.universe = v.column1 AND o.title = v.column2
);
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);

console.log(`wrote ${OUT}`);
console.log(`  universes: ${sectionCount}`);
console.log(`  title rows: ${titleCount}`);
console.log(`  crossover rows skipped: ${crossoverCount}`);
